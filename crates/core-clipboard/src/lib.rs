#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Text,
    Link,
    Code,
    Image,
    File,
}

impl Kind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Kind::Text => "text",
            Kind::Link => "link",
            Kind::Code => "code",
            Kind::Image => "image",
            Kind::File => "file",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Some(match s {
            "text" => Kind::Text,
            "link" => Kind::Link,
            "code" => Kind::Code,
            "image" => Kind::Image,
            "file" => Kind::File,
            _ => return None,
        })
    }
}

/// Pasteboard types meaning "do not keep this" (nspasteboard.org convention, plus 1Password's legacy marker).
const SKIPPED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// Whether a pasteboard item carrying these types may be stored in history.
pub fn should_record<'a>(types: impl IntoIterator<Item = &'a str>) -> bool {
    !types.into_iter().any(|t| SKIPPED_TYPES.contains(&t))
}

/// Apps whose copies are never stored, on top of the user's own list.
pub const DEFAULT_IGNORED_APPS: &[&str] = &[
    "com.1password.1password",
    "com.agilebits.onepassword7",
    "com.agilebits.onepassword-osx",
    "com.bitwarden.desktop",
    "org.keepassxc.keepassxc",
    "com.lastpass.LastPass",
    "com.apple.keychainaccess",
    "com.apple.Passwords",
];

pub fn is_ignored_app(bundle_id: &str, extra: &[String]) -> bool {
    DEFAULT_IGNORED_APPS.contains(&bundle_id) || extra.iter().any(|a| a == bundle_id)
}

/// Heuristic classification; it only drives the `@link` / `@code` filters, so a wrong guess is cheap.
pub fn classify_text(text: &str) -> Kind {
    let t = text.trim();
    if is_link(t) {
        Kind::Link
    } else if looks_like_code(t) {
        Kind::Code
    } else {
        Kind::Text
    }
}

fn is_link(t: &str) -> bool {
    if t.is_empty() || t.contains(char::is_whitespace) {
        return false;
    }
    let lower = t.to_lowercase();
    ["http://", "https://", "ftp://", "mailto:"]
        .iter()
        .any(|p| lower.starts_with(p))
        || (lower.starts_with("www.") && lower[4..].contains('.'))
}

fn looks_like_code(t: &str) -> bool {
    let lines: Vec<&str> = t.lines().collect();
    if lines.len() < 2 {
        return false;
    }
    let total = t.chars().count().max(1);
    let symbols = t.chars().filter(|c| "{}();=<>[]".contains(*c)).count();
    let ratio = symbols as f64 / total as f64;
    let indented = lines
        .iter()
        .filter(|l| l.starts_with("    ") || l.starts_with('\t'))
        .count();
    const KEYWORDS: [&str; 14] = [
        "fn ",
        "def ",
        "function ",
        "class ",
        "import ",
        "#include",
        "return ",
        "const ",
        "let ",
        "var ",
        "select ",
        "public ",
        "struct ",
        "use ",
    ];
    let keyword_lines = lines
        .iter()
        .filter(|l| {
            let l = l.trim_start().to_lowercase();
            KEYWORDS.iter().any(|k| l.starts_with(k))
        })
        .count();
    ratio > 0.06 || (keyword_lines >= 1 && (ratio > 0.02 || indented >= 1))
}

/// One-line display title: first non-empty line, whitespace collapsed, capped at 200 characters.
pub fn title_of(text: &str) -> String {
    let line = text
        .lines()
        .map(str::trim)
        .find(|l| !l.is_empty())
        .unwrap_or("");
    let mut out = String::new();
    let mut prev_space = false;
    for c in line.chars().take(200) {
        if c.is_whitespace() {
            if !prev_space {
                out.push(' ');
            }
            prev_space = true;
        } else {
            out.push(c);
            prev_space = false;
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skips_concealed_data_only() {
        assert!(should_record(["public.utf8-plain-text", "public.html"]));
        assert!(!should_record([
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType"
        ]));
    }

    #[test]
    fn ignores_password_managers() {
        assert!(is_ignored_app("com.1password.1password", &[]));
        assert!(is_ignored_app(
            "com.example.vault",
            &["com.example.vault".into()]
        ));
        assert!(!is_ignored_app("com.apple.Safari", &[]));
    }

    #[test]
    fn classifies_links_code_and_plain_text() {
        assert_eq!(classify_text("https://example.com/a?b=1"), Kind::Link);
        assert_eq!(classify_text("  www.example.com  "), Kind::Link);
        assert_eq!(classify_text("see https://example.com now"), Kind::Text);
        assert_eq!(
            classify_text("Xin chào, hôm nay trời đẹp.\nĐi chơi nhé."),
            Kind::Text
        );
        let rust = "fn main() {\n    let x = vec![1, 2];\n    println!(\"{:?}\", x);\n}";
        assert_eq!(classify_text(rust), Kind::Code);
        let js = "const a = 1;\nfunction f(x) {\n  return x + a;\n}";
        assert_eq!(classify_text(js), Kind::Code);
        assert_eq!(classify_text("single line;"), Kind::Text);
    }

    #[test]
    fn title_collapses_whitespace_and_skips_blank_lines() {
        assert_eq!(title_of("\n\n   hello \t  world  \nsecond"), "hello world");
        assert_eq!(title_of("   "), "");
        assert_eq!(title_of(&"x".repeat(500)).chars().count(), 200);
    }
}
