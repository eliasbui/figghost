const said = new Set<string>();

export function Icon({ name, className, weight, size }: { name: string; className?: string; weight?: IconWeight; size?: number | string }) {
  const entry = ICONS[name];
  if (!entry) {
    if (import.meta.env.DEV && !said.has(name)) {
      said.add(name);
      console.warn(`icon without a picture: ${name}`);
    }
    return <span className={cn('glyph', className)} style={{ visibility: 'hidden' }} aria-hidden="true" />;
  }
  const [Glyph, own] = entry;
  return (
    <span className={cn('glyph', className)} aria-hidden="true">
      <Glyph weight={weight ?? own ?? 'regular'} size={size ?? '100%'} />
    </span>
  );
}
